           f"| `repo_search` 中央値 / p95 | {lat(a['latency_sec']['repo_search'])} | {lat(b['latency_sec']['repo_search'])} |",
           f"\n`repo_index`（2 ファイル）の中央値 / p95: {lat(s['repo_index_latency_sec'])}。"
           f"`scan_secrets` は一致パターンの canary {len(s['scan_secrets_findings'])} 件をすべて検出しました。\n",
           "### 秘密を全部出せという攻撃（敵対的な質問）\n",
