def load(uc: str, name: str = "summary.json"):
    return json.loads((RESULTS / uc / name).read_text(encoding="utf-8"))


def raw(uc: str) -> list[dict]:
    return [json.loads(l) for l in (RESULTS / uc / "raw.jsonl").read_text(encoding="utf-8").splitlines() if l]


def pct(x) -> str:
    return "—" if x is None else f"{x * 100:.0f}%"


def lat(s: dict | None, unit: str = "s") -> str:
    return "—" if not s else f"{s['median']:.2f} / {s['p95']:.2f} {unit}（SD {s['stdev']:.2f}）"


def media(prefix: str, uc: str, title: str) -> str:
    return (f"**実行の録画**（実時間。MP4: [{uc}-demo.mp4]({prefix}media/{uc}-demo.mp4)）\n\n"
            f"![{title}]({prefix}media/{uc}-demo.gif)\n\n"
            f"| 途中 | 最後（実測サマリ） |\n|---|---|\n"
            f"| ![{uc} mid]({prefix}media/{uc}-shot-mid.png) | ![{uc} final]({prefix}media/{uc}-shot-final.png) |\n\n"
            f"独立した `nvidia-smi` ログ（ツールとは別プロセスで 250 ms ごとに取得。網掛けは計測区間）:\n\n"
            f"![{uc} GPU timeline]({prefix}media/{uc}-gpu-timeline.svg)\n")


